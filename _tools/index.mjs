#!/usr/bin/env node
// Rebuilds the two generated indexes from what is on disk. Never edit the indexes by hand.
//   05_decide/amendments/_index.md: one row per amendment record (from its frontmatter), then every amendment
//     heading in the frozen TEST_METHOD.md with its line number.
//   runs/_index.md: one row per run folder: model, sessions, the gate's verdict (check.md first line), and a
//     person's clearing (cleared.md first line) where there is one.
// Use: node _tools/index.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib.mjs';

const first = f => existsSync(f) ? readFileSync(f, 'utf8').split(/\r?\n/)[0].trim() : '';
const cell = s => String(s).replace(/\|/g, '/');

// Amendments
const A = join(ROOT, '05_decide', 'amendments');
const recs = readdirSync(A).filter(f => /^\d{3}-.+\.md$/.test(f)).sort().map(f => {
  const fm = readFileSync(join(A, f), 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] ?? '';
  const get = k => fm.match(new RegExp(`^${k}:\\s*(.*)$`, 'm'))?.[1]?.trim() ?? '';
  return `| ${get('number')} | [${cell(get('title'))}](${f}) | ${get('status')} | ${get('written')} | ${get('persona_commit')} |`;
});
const tm = readFileSync(join(ROOT, '05_decide', 'TEST_METHOD.md'), 'utf8').split(/\r?\n/);
const old = tm.map((l, i) => [l, i + 1]).filter(([l]) => /^## Amendment/.test(l))
  .map(([l, n]) => `| ${n} | ${cell(l.replace(/^## /, '').slice(0, 150))} |`);
writeFileSync(join(A, '_index.md'), [
  '# Amendments: index', '',
  'Generated by `node _tools/index.mjs`; do not edit. Every change to the persona or the method, newest record last.', '',
  '## Records (one file each, from Amendment 30)', '',
  '| # | Title | Status | Written | Persona commit |', '|---|---|---|---|---|', ...recs, '',
  '## In the frozen record, `../TEST_METHOD.md` (Amendments 1 to 29; a result can sit under a later heading)', '',
  '| Line | Heading |', '|---|---|', ...old, ''].join('\n'));

// Runs
const R = join(ROOT, 'runs');
const rows = readdirSync(R).filter(d => statSync(join(R, d)).isDirectory()).sort().map(d => {
  const p = join(R, d), js = readdirSync(p).filter(f => f.endsWith('.json'));
  const models = new Set();
  for (const f of js) { try { const m = JSON.parse(readFileSync(join(p, f), 'utf8')).meta?.model; if (m) models.add(m); } catch {} }
  const gate = first(join(p, 'check.md')) || 'no check.md';
  const cleared = first(join(p, 'cleared.md'));
  return `| ${d} | ${[...models].join(', ') || '-'} | ${js.length} | ${cell(gate.replace(/ \(a person reads.*$/, ''))} | ${cell(cleared)} |`;
});
writeFileSync(join(R, '_index.md'), [
  '# Runs: index', '',
  'Generated by `node _tools/index.mjs`; do not edit. One row per run. "Gate" is the first line of the run\'s',
  '`check.md` (today\'s scanner and leak check); "Cleared" is a person\'s reading in `cleared.md`. Older runs were',
  'also read when they ran: their amendment in `05_decide/` says what was found then. Read from the FAIL lines on',
  '2026-11-14, most older fails are one of three kinds: checks stricter than when the run happened (the debrief',
  'format changed several times, so C10 fails), runs built to fail (the weak persona, Haiku, the control prompts,',
  'the early drafts), or sessions where stepping out is right (a child, real distress, a withdrawn consent).', '',
  'Model is as each run recorded it; some early runs recorded the Haiku side call instead (fixed by Amendment 26b).', '',
  '| Run | Model | Sessions | Gate | Cleared |', '|---|---|---|---|---|', ...rows, ''].join('\n'));
console.log(`amendments: ${recs.length} records, ${old.length} in the frozen record; runs: ${rows.length}`);
